import { Currency, Language } from '../types/vehicle';

export const CURRENCY_RATES: Record<Currency, number> = {
  AZN: 1.0,
  USD: 1.70, // 1 USD = 1.70 AZN
  EUR: 1.85, // 1 EUR = 1.85 AZN
};

export const formatPrice = (amountAzn: number, currency: Currency): string => {
  let converted = amountAzn;
  let symbol = '₼';

  if (currency === 'USD') {
    converted = amountAzn / CURRENCY_RATES.USD;
    symbol = '$';
  } else if (currency === 'EUR') {
    converted = amountAzn / CURRENCY_RATES.EUR;
    symbol = '€';
  }

  const rounded = Math.round(converted);
  return `${rounded.toLocaleString('en-US')} ${symbol}`;
};

