export function getSellerDossierForVehicle(vehicle: Vehicle): SellerIdentityDossier {
  const sellerId = vehicle.seller?.id || 'seller_default';
  const predefined = MOCK_SELLER_DOSSIERS[sellerId];

  if (predefined) {
    return {
      sellerId,
      fullName: predefined.fullName || vehicle.seller.name,
      sellerType: predefined.sellerType || (vehicle.seller.type === 'official_dealer' ? 'official_dealer' : 'private'),
      finCodeMasked: predefined.finCodeMasked || '6A***9X',
      asanLoginVerified: predefined.asanLoginVerified ?? true,
      asanVerificationDate: predefined.asanVerificationDate || '2026-02-10',
      dypTexpasportMatch: predefined.dypTexpasportMatch || 'owner_matched',
      dypOwnerName: predefined.dypOwnerName || vehicle.seller.name,
      texpasportSeriesNumber: predefined.texpasportSeriesNumber || 'AA 741203',
      biometricVerified: predefined.biometricVerified ?? true,
      phoneVerified: predefined.phoneVerified ?? true,
      legalStatus: predefined.legalStatus || 'clean',
      hasActiveEnforcement: predefined.hasActiveEnforcement ?? false,
      hasPoliceWantedCheck: predefined.hasPoliceWantedCheck ?? true,
      trustScore: predefined.trustScore || 90,
      trustLevel: predefined.trustLevel || 'verified_owner',
      totalDealsCompleted: predefined.totalDealsCompleted ?? 6,
      disputeRatePercent: predefined.disputeRatePercent ?? 0.0,
      memberSinceYear: vehicle.seller.memberSinceYear || 2022,
      city: vehicle.seller.city || vehicle.city || 'Bakı',
    };
  }

  // Generate dynamic dossier based on vehicle seller
  const isDealer = vehicle.seller?.type === 'official_dealer' || vehicle.seller?.type === 'autocenter';
  const name = vehicle.seller?.name || 'Mülkiyyətçi';
  
  return {
    sellerId,
    fullName: name,
    sellerType: isDealer ? (vehicle.seller?.type === 'official_dealer' ? 'official_dealer' : 'autocenter') : 'private',
    finCodeMasked: '7P***3K',
    asanLoginVerified: vehicle.seller?.verifiedIdentity ?? true,
    asanVerificationDate: '2026-03-12',
    dypTexpasportMatch: 'owner_matched',
    dypOwnerName: name,
    texpasportSeriesNumber: 'AA 419208',
    biometricVerified: true,
    phoneVerified: true,
    legalStatus: 'clean',
    hasActiveEnforcement: false,
    hasPoliceWantedCheck: true,
    trustScore: isDealer ? 96 : 89,
    trustLevel: isDealer ? 'elite_dealer' : 'verified_owner',
    totalDealsCompleted: isDealer ? 55 : 3,
    disputeRatePercent: 0.0,
    memberSinceYear: vehicle.seller?.memberSinceYear || 2023,
    city: vehicle.seller?.city || vehicle.city || 'Bakı',
  };
}
